-- Upsert only the current batch into CORE.ORDERS (idempotent: re-running a batch changes nothing new).
-- {batch_id} is substituted by etl.load; it is a generated token (YYYYMMDDTHHMMSS_xxxx), never user input.
MERGE INTO CORE.ORDERS t
USING (
    SELECT * FROM RAW.ORDERS_STG WHERE BATCH_ID = '{batch_id}'
) s
ON t.ORDER_ID = s.ORDER_ID
WHEN MATCHED AND (
        NOT EQUAL_NULL(t.STATUS, s.STATUS)
     OR NOT EQUAL_NULL(t.QUANTITY, s.QUANTITY)
     OR NOT EQUAL_NULL(t.UNIT_PRICE, s.UNIT_PRICE)
     OR NOT EQUAL_NULL(t.ORDER_DATE, s.ORDER_DATE)
     OR NOT EQUAL_NULL(t.NET_REVENUE, s.NET_REVENUE)
) THEN UPDATE SET
    CUSTOMER_ID = s.CUSTOMER_ID, PRODUCT = s.PRODUCT, CATEGORY = s.CATEGORY,
    QUANTITY = s.QUANTITY, UNIT_PRICE = s.UNIT_PRICE, ORDER_DATE = s.ORDER_DATE,
    STATUS = s.STATUS, COUNTRY = s.COUNTRY, GROSS_AMOUNT = s.GROSS_AMOUNT,
    NET_REVENUE = s.NET_REVENUE, LAST_BATCH_ID = s.BATCH_ID, UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
    (ORDER_ID, CUSTOMER_ID, PRODUCT, CATEGORY, QUANTITY, UNIT_PRICE, ORDER_DATE,
     STATUS, COUNTRY, GROSS_AMOUNT, NET_REVENUE, LAST_BATCH_ID)
VALUES
    (s.ORDER_ID, s.CUSTOMER_ID, s.PRODUCT, s.CATEGORY, s.QUANTITY, s.UNIT_PRICE, s.ORDER_DATE,
     s.STATUS, s.COUNTRY, s.GROSS_AMOUNT, s.NET_REVENUE, s.BATCH_ID)
