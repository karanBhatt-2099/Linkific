-- Incremental mart refresh: rebuild only the dates touched by this batch.
-- Step 1: remove affected dates. Step 2: re-aggregate them from CORE (pruned by CLUSTER BY ORDER_DATE).
DELETE FROM MART.DAILY_SALES
WHERE ORDER_DATE IN (SELECT DISTINCT ORDER_DATE FROM RAW.ORDERS_STG WHERE BATCH_ID = '{batch_id}');

INSERT INTO MART.DAILY_SALES
    (ORDER_DATE, COUNTRY, CATEGORY, ORDERS, UNITS, GROSS_AMOUNT, NET_REVENUE, CANCELLED_ORDERS)
SELECT ORDER_DATE, COUNTRY, CATEGORY,
       COUNT(*), SUM(QUANTITY), SUM(GROSS_AMOUNT), SUM(NET_REVENUE),
       COUNT_IF(STATUS = 'cancelled')
FROM CORE.ORDERS
WHERE ORDER_DATE IN (SELECT DISTINCT ORDER_DATE FROM RAW.ORDERS_STG WHERE BATCH_ID = '{batch_id}')
GROUP BY ORDER_DATE, COUNTRY, CATEGORY
