"""Runs every query in queries/01..05 against data/sales.db, prints PASS/FAIL,
and writes the first rows of each result to output/query_results.md"""
import sqlite3, os, re, glob, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
con = sqlite3.connect(os.path.join(ROOT, "data", "sales.db"))
out, failed, total = ["# Query Results (auto-generated by scripts/run_all.py)\n"], [], 0

def fmt(rows, cols):
    if not rows: return "_(no rows)_"
    w = [max(len(str(c)), *(len(str(r[i])) for r in rows)) for i, c in enumerate(cols)]
    line = lambda vals: "| " + " | ".join(str(v).ljust(w[i]) for i, v in enumerate(vals)) + " |"
    return "\n".join([line(cols), "|" + "|".join("-"*(x+2) for x in w) + "|"] + [line(r) for r in rows])

for path in sorted(glob.glob(os.path.join(ROOT, "queries", "0[1-5]_*.sql"))):
    out.append(f"\n---\n## {os.path.basename(path)}\n")
    text = open(path).read()
    blocks = re.split(r"(?m)^-- (Q\d+): ", text)[1:]
    for qid, body in zip(blocks[0::2], blocks[1::2]):
        title, _, sql = body.partition("\n")
        total += 1
        try:
            cur = con.execute(sql.strip().rstrip(";"))
            rows = cur.fetchall(); cols = [d[0] for d in cur.description]
            print(f"PASS {qid} ({len(rows):3d} rows)  {title[:70]}")
            out.append(f"### {qid}: {title}\n```sql\n{sql.strip()}\n```\n{fmt(rows[:12], cols)}\n")
        except Exception as e:
            failed.append(qid); print(f"FAIL {qid}: {e}")
            out.append(f"### {qid}: {title}\n**FAILED:** {e}\n")

open(os.path.join(ROOT, "output", "query_results.md"), "w").write("\n".join(out))
print(f"\n{total-len(failed)}/{total} queries passed" + (f"; failed: {failed}" if failed else ""))
sys.exit(1 if failed else 0)
