-- ------------------------- (a) SNOWFLAKE -----------------------------
TRUNCATE dw_snowflake.fact_sales, dw_snowflake.dim_product,
         dw_snowflake.dim_subcategory, dw_snowflake.dim_category,
         dw_snowflake.dim_store, dw_snowflake.dim_region
RESTART IDENTITY CASCADE;

INSERT INTO dw_snowflake.dim_category (category_name)
SELECT DISTINCT category FROM dw.dim_product ORDER BY 1;

INSERT INTO dw_snowflake.dim_subcategory (subcategory_name, category_key)
SELECT DISTINCT p.subcategory, c.category_key
FROM   dw.dim_product p
JOIN   dw_snowflake.dim_category c ON c.category_name = p.category
ORDER  BY 2, 1;

INSERT INTO dw_snowflake.dim_product
       (product_key, product_id, product_name, brand, unit_cost, unit_price, subcategory_key)
SELECT p.product_key, p.product_id, p.product_name, p.brand, p.unit_cost, p.unit_price,
       sc.subcategory_key
FROM   dw.dim_product p
JOIN   dw_snowflake.dim_category    c  ON c.category_name     = p.category
JOIN   dw_snowflake.dim_subcategory sc ON sc.subcategory_name = p.subcategory
                                      AND sc.category_key     = c.category_key;

INSERT INTO dw_snowflake.dim_region (region_name)
SELECT DISTINCT region FROM dw.dim_store ORDER BY 1;

INSERT INTO dw_snowflake.dim_store
       (store_key, store_id, store_name, city, state, store_type, region_key)
SELECT s.store_key, s.store_id, s.store_name, s.city, s.state, s.store_type, r.region_key
FROM   dw.dim_store s
JOIN   dw_snowflake.dim_region r ON r.region_name = s.region;

INSERT INTO dw_snowflake.fact_sales
SELECT sales_key, date_key, customer_key, product_key, store_key,
       order_id, quantity, sales_amount, profit_amount
FROM   dw.fact_sales;

-- ------------------------- (b) GALAXY --------------------------------
-- Month-end inventory snapshots for Jan-Jun 2026, 12 products x 4 stores
-- = 6 x 12 x 4 = 288 rows. Quantities are generated by a simple
-- deterministic formula so you always get the same numbers.
TRUNCATE dw.fact_inventory RESTART IDENTITY;

INSERT INTO dw.fact_inventory (date_key, product_key, store_key, quantity_on_hand, reorder_level)
SELECT d.date_key,
       p.product_key,
       s.store_key,
       ((p.product_key * 7 + s.store_key * 13 + d.month_number * 5) % 40) + 5 AS quantity_on_hand,
       10                                                                     AS reorder_level
FROM   dw.dim_date d
CROSS  JOIN dw.dim_product p
CROSS  JOIN dw.dim_store   s
WHERE  d.year = 2026
  AND  d.month_number BETWEEN 1 AND 6
  AND  d.full_date = (DATE_TRUNC('month', d.full_date) + INTERVAL '1 month - 1 day')::DATE;  -- month-end

-- Validation: expect snowflake fact = 27 rows, inventory = 288 rows
SELECT (SELECT COUNT(*) FROM dw_snowflake.fact_sales) AS snowflake_fact_rows,
       (SELECT COUNT(*) FROM dw.fact_inventory)       AS inventory_rows;
