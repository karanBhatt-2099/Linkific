-- Run once in Snowflake before the first load.
CREATE TABLE IF NOT EXISTS ETL_WATERMARK (
    TABLE_NAME       VARCHAR PRIMARY KEY,
    LAST_UPDATED_AT  VARCHAR,          -- 'yyyy-MM-dd HH:mm:ss', highest updated_at loaded so far
    LOADED_AT        TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS DIM_PATIENTS (
    PATIENT_ID  VARCHAR PRIMARY KEY,
    FULL_NAME   VARCHAR,
    DOB         DATE,
    GENDER      VARCHAR,
    PHONE       VARCHAR,
    EMAIL       VARCHAR,
    UPDATED_AT  TIMESTAMP_NTZ,
    AGE         NUMBER,
    AGE_GROUP   VARCHAR
);

CREATE TABLE IF NOT EXISTS DIM_DOCTORS (
    DOCTOR_ID    VARCHAR PRIMARY KEY,
    DOCTOR_NAME  VARCHAR,
    DEPARTMENT   VARCHAR,
    UPDATED_AT   TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS FACT_APPOINTMENTS (
    APPOINTMENT_ID     VARCHAR PRIMARY KEY,
    PATIENT_ID         VARCHAR,
    PATIENT_NAME       VARCHAR,
    PATIENT_AGE_GROUP  VARCHAR,
    DOCTOR_ID          VARCHAR,
    DOCTOR_NAME        VARCHAR,
    DEPARTMENT         VARCHAR,
    APPOINTMENT_DATE   DATE,
    APPOINTMENT_MONTH  VARCHAR,
    STATUS             VARCHAR,
    FEE                DOUBLE,
    FEE_BAND           VARCHAR,
    REVENUE            DOUBLE,
    UPDATED_AT         TIMESTAMP_NTZ
);

-- Rebuilt in full on every run, so column order must match the Spark output.
CREATE TABLE IF NOT EXISTS DOCTOR_MONTHLY_SUMMARY (
    DOCTOR_ID           VARCHAR,
    DOCTOR_NAME         VARCHAR,
    DEPARTMENT          VARCHAR,
    APPOINTMENT_MONTH   VARCHAR,
    TOTAL_APPOINTMENTS  NUMBER,
    COMPLETED           NUMBER,
    CANCELLED           NUMBER,
    NO_SHOWS            NUMBER,
    TOTAL_REVENUE       DOUBLE,
    AVG_FEE             DOUBLE,
    UNIQUE_PATIENTS     NUMBER,
    CANCELLATION_RATE   DOUBLE
);
