-- Run once in Snowflake
CREATE WAREHOUSE IF NOT EXISTS PIPELINE_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS PRODUCT_DB;
CREATE SCHEMA IF NOT EXISTS PRODUCT_DB.RAW;
CREATE SCHEMA IF NOT EXISTS PRODUCT_DB.ANALYTICS;

CREATE TABLE IF NOT EXISTS PRODUCT_DB.RAW.PRODUCTS (
  id        INT,
  title     STRING,
  category  STRING,
  price     FLOAT,
  stock     INT,
  rating    FLOAT,
  loaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

CREATE STAGE IF NOT EXISTS PRODUCT_DB.RAW.PRODUCT_STAGE;
